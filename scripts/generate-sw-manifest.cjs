#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT_DIR = path.resolve(__dirname, '..');
const WWW_DIR = path.join(ROOT_DIR, 'www');
const OUTPUT_FILE = path.join(WWW_DIR, 'sw-assets.js');

const EXCLUDED_FILES = new Set([
    'input.css',
    'tailwind.config.js',
    'sw.js',
    'sw-assets.js'
]);

function toPosix(relPath) {
    return relPath.split(path.sep).join('/');
}

function walkFiles(dir) {
    const entries = fs.readdirSync(dir, {withFileTypes: true});
    const all = [];
    for (const entry of entries) {
        const abs = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            all.push(...walkFiles(abs));
            continue;
        }
        all.push(abs);
    }
    return all;
}

function buildAssetList() {
    const allFiles = walkFiles(WWW_DIR);
    const assets = ['./'];
    for (const file of allFiles) {
        const rel = toPosix(path.relative(WWW_DIR, file));
        if (EXCLUDED_FILES.has(rel)) continue;
        assets.push(`./${rel}`);
    }
    return assets.sort();
}

function hashAssets(assets) {
    const hasher = crypto.createHash('sha1');
    for (const asset of assets) {
        hasher.update(asset);
        if (asset === './') continue;
        const abs = path.join(WWW_DIR, asset.replace(/^\.\//, ''));
        hasher.update(fs.readFileSync(abs));
    }
    return hasher.digest('hex').slice(0, 12);
}

function writeManifest() {
    const assets = buildAssetList();
    const revision = hashAssets(assets);
    const cacheName = `tahara-${revision}`;

    const out = [
        '// Auto-generated by scripts/generate-sw-manifest.cjs',
        '// Do not edit manually.',
        `self.__TAHARA_SW_MANIFEST = ${JSON.stringify({cacheName, assets}, null, 4)};`,
        ''
    ].join('\n');

    fs.writeFileSync(OUTPUT_FILE, out, 'utf8');
    return {cacheName, assetCount: assets.length};
}

if (require.main === module) {
    const {cacheName, assetCount} = writeManifest();
    console.log(`Generated ${path.relative(ROOT_DIR, OUTPUT_FILE)} (${assetCount} assets, cache: ${cacheName})`);
}

module.exports = {
    EXCLUDED_FILES,
    OUTPUT_FILE,
    WWW_DIR,
    buildAssetList,
    writeManifest
};
